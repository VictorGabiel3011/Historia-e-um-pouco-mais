// FUNÇÃO PARA TROCAR DE PÁGINA

function abrirPagina(id) {

    // Esconde todas as páginas

    document.querySelectorAll(".pagina").forEach(pagina => {

        pagina.classList.remove("ativa");

    });


    // Remove a seleção de todas as abas

    document.querySelectorAll(".aba").forEach(aba => {

        aba.classList.remove("ativa");

    });


    // Localiza a página selecionada

    const pagina = document.getElementById(id);

    const aba = document.querySelector(
        `.aba[data-page="${id}"]`
    );


    // Verifica se a página existe

    if (!pagina) return;


    // Mostra a página selecionada

    pagina.classList.add("ativa");


    // Destaca a aba selecionada

    if (aba) {

        aba.classList.add("ativa");

    }


    // Volta para o topo

    window.scrollTo({

        top: 0,
        behavior: "smooth"

    });

}


// EVENTO DE CLIQUE NAS ABAS

document.querySelectorAll(".aba").forEach(botao => {

    botao.addEventListener("click", () => {

        abrirPagina(botao.dataset.page);

    });

});


// EVENTO DE CLIQUE NOS CARTÕES DA PÁGINA INICIAL

document.querySelectorAll("[data-go]").forEach(botao => {

    botao.addEventListener("click", () => {

        abrirPagina(botao.dataset.go);

    });

});
